// Scans art/portraits and art/scenes and writes js/art.js, telling the game which
// illustrations exist. Characters without one keep their drawn portrait.
// Usage: node art-manifest.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const scan = dir => {
  const out = {};
  const full = path.join(root, 'art', dir);
  if (!fs.existsSync(full)) return out;
  for (const f of fs.readdirSync(full).sort()) {
    const m = f.match(/^([a-zA-Z-]+)\.(jpe?g|png|webp)$/i);
    if (m) out[m[1]] = `art/${dir}/${f}`;
  }
  return out;
};
const art = { portraits: scan('portraits'), scenes: scan('scenes') };
fs.writeFileSync(path.join(root, 'js/art.js'),
  `// Generated by tools/art-manifest.mjs from the files in art/.\nwindow.ART = ${JSON.stringify(art, null, 2)};\n`);
console.log(`portraits: ${Object.keys(art.portraits).length}, scenes: ${Object.keys(art.scenes).length}`);
